/**
 * Shared export for PO Search result tables (CRN, R-NOTE, ...).
 *
 * This is DocLink's equivalent of the portal's "Export to Excel" button
 * under a result table - except that it exports every row IREPS returned,
 * not only the rows visible on the current DataTables page.
 *
 * Formats:
 *   xlsx (default)  Excel workbook: one data sheet (header row + one row per
 *                   record, frozen header, auto-filter) and a sheet "Info"
 *                   (source, retrieval time, filter, record count)
 *   csv             the same table as UTF-8 CSV
 *
 * The type-specific modules (services/crn/crn-export.js,
 * services/rnote/rnote-export.js) decide the columns; this module only
 * writes the file. Nothing here assumes a PDF or any particular format: the
 * download layer receives { bytes, mimeType, extension }.
 */

import { buildWorkbook, buildCsv, XLSX_MIME_TYPE, CSV_MIME_TYPE } from "../../utils/xlsx-writer.js";
import { formatDisplayTimestamp } from "../../utils/filename.js";

export const EXPORT_FORMAT = Object.freeze({ XLSX: "xlsx", CSV: "csv" });

export const EXPORT_FORMATS = Object.freeze([
  { value: EXPORT_FORMAT.XLSX, label: "Excel (.xlsx)", mimeType: XLSX_MIME_TYPE, extension: "xlsx" },
  { value: EXPORT_FORMAT.CSV, label: "CSV (.csv)", mimeType: CSV_MIME_TYPE, extension: "csv" }
]);

export function exportFormatInfo(format) {
  return EXPORT_FORMATS.find((f) => f.value === format) || EXPORT_FORMATS[0];
}

/**
 * @typedef {Object} ExportFile
 * @property {Uint8Array} bytes
 * @property {string} mimeType
 * @property {string} extension     "xlsx" | "csv"
 * @property {string} format
 * @property {number} recordCount
 * @property {number} columnCount
 */

/**
 * Build the export file for one result table.
 *
 * @param {{ sheetName: string, documentLabel: string, sourceLabel: string, headers: string[], rows: (string|null)[][],
 *          filter?: string, fetchedAt?: string, pagesFetched?: number, warnings?: string[] }} table
 * @param {{ format?: string, now?: Date }} [options]
 * @returns {ExportFile}
 */
export function buildTableExport(table, options = {}) {
  if (!table || !Array.isArray(table.headers) || !Array.isArray(table.rows)) throw new Error("Invalid export table");
  const info = exportFormatInfo(options.format);
  const now = options.now instanceof Date ? options.now : new Date();
  const { headers, rows } = table;

  let bytes;
  if (info.value === EXPORT_FORMAT.CSV) {
    bytes = buildCsv(headers, rows);
  } else {
    const retrieved = table.fetchedAt ? formatDisplayTimestamp(new Date(table.fetchedAt)) : formatDisplayTimestamp(now);
    const infoRows = [
      ["Document", `IREPS ${table.documentLabel} search results`],
      ["Source", table.sourceLabel],
      ["Retrieved", retrieved],
      ["Filter", table.filter || ""],
      ["Records", String(rows.length)],
      ["Result pages fetched", String(table.pagesFetched || 1)],
      ["Generated by", "DocLink"],
      ["Note", "Values are copied exactly as IREPS returned them; nothing is calculated or inferred."]
    ];
    if (table.warnings && table.warnings.length) infoRows.push(["Warnings", table.warnings.join("\n")]);
    bytes = buildWorkbook({
      title: `IREPS ${table.documentLabel} Search - ${retrieved}`,
      creator: "DocLink",
      date: now,
      sheets: [
        { name: table.sheetName, headers, rows },
        { name: "Info", headers: ["Field", "Value"], rows: infoRows, columnWidths: [22, 90], autoFilter: false, freezeHeader: false }
      ]
    });
  }
  return { bytes, mimeType: info.mimeType, extension: info.extension, format: info.value, recordCount: rows.length, columnCount: headers.length };
}
